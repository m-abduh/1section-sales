"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import Link from "next/link";
import {
  AlertTriangle,
  ArrowLeft,
  CheckCircle2,
  Download,
  ExternalLink,
  FileText,
  Pencil,
  RefreshCw,
  UploadCloud,
} from "lucide-react";
import {
  downloadEbookDocx,
  downloadEbookPdf,
  fetchEbookPdf,
  useEbookProject,
  usePublishEbookProject,
  useUpdateEbookProject,
  type PublishEbookInput,
} from "@/hooks/use-builder";
import { useAdminNiches } from "@/hooks/use-admin-niches";
import type { ProductInput } from "@/hooks/use-admin-products";
import { getApiErrorMessage } from "@/lib/api";
import { formatDate } from "@/lib/format";
import { Button } from "@/components/ui/button";
import { Modal } from "@/components/admin/modal";
import { ProductForm } from "@/components/admin/product-form";
import { Spinner } from "@/components/ui/spinner";

export function EbookPreview({ projectId }: { projectId: string }) {
  const project = useEbookProject(projectId);
  const updateProject = useUpdateEbookProject();
  const [pdfSrc, setPdfSrc] = useState<string | null>(null);
  const [pdfLoading, setPdfLoading] = useState(false);
  const [pdfError, setPdfError] = useState<string | null>(null);
  const [statusError, setStatusError] = useState<string | null>(null);
  const [publishOpen, setPublishOpen] = useState(false);
  const [published, setPublished] = useState<string | null>(null);
  const autoGenerated = useRef(false);

  const data = project.data;
  const status = data?.status === "final" ? "final" : "draft";
  const canExportPdf = status === "final";

  useEffect(() => {
    return () => {
      if (pdfSrc) URL.revokeObjectURL(pdfSrc);
    };
  }, [pdfSrc]);

  const loadPdf = useCallback(async () => {
    if (!canExportPdf) return;
    setPdfError(null);
    setPdfLoading(true);
    try {
      const blob = await fetchEbookPdf(projectId);
      setPdfSrc((previous) => {
        if (previous) URL.revokeObjectURL(previous);
        return URL.createObjectURL(blob);
      });
    } catch (caught) {
      setPdfError(
        caught instanceof Error ? caught.message : "Gagal membuat PDF.",
      );
    } finally {
      setPdfLoading(false);
    }
  }, [canExportPdf, projectId]);

  // PDFKit is the source of truth for layout, so the preview is generated
  // automatically as soon as the ebook is marked final.
  useEffect(() => {
    if (status !== "final" || pdfSrc || pdfLoading) return;
    if (autoGenerated.current) return;
    autoGenerated.current = true;
    void loadPdf();
  }, [status, pdfSrc, pdfLoading, loadPdf]);

  async function markFinal() {
    setStatusError(null);
    try {
      await updateProject.mutateAsync({
        id: projectId,
        input: { status: "final" },
      });
    } catch (caught) {
      setStatusError(getApiErrorMessage(caught));
    }
  }

  async function handleDownload(kind: "docx" | "pdf") {
    if (!data) return;
    try {
      if (kind === "docx") {
        await downloadEbookDocx(projectId, data.title);
      } else {
        await downloadEbookPdf(projectId, data.title);
      }
    } catch (caught) {
      setPdfError(getApiErrorMessage(caught));
    }
  }

  if (project.isLoading) {
    return (
      <div className="flex items-center gap-2 text-sm text-fg-muted">
        <Spinner /> Loading ebook...
      </div>
    );
  }

  if (project.isError || !data) {
    return (
      <div className="rounded-2xl border border-border bg-card p-6 text-sm text-fg-muted">
        Ebook tidak ditemukan.{" "}
        <Link href="/admin/builder" className="font-medium text-fg underline">
          Kembali ke builder
        </Link>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <Link
          href={`/admin/builder/${projectId}`}
          className="inline-flex items-center gap-2 text-xs font-medium text-fg-muted transition hover:text-fg"
        >
          <ArrowLeft className="size-3.5" />
          Kembali ke editor
        </Link>

        <div className="flex flex-wrap items-center gap-2">
          <Button
            variant="secondary"
            size="sm"
            onClick={() => void handleDownload("docx")}
          >
            <Download className="size-3.5" />
            Download DOCX
          </Button>
          {canExportPdf ? (
            <Button
              variant="secondary"
              size="sm"
              onClick={() => void handleDownload("pdf")}
            >
              <Download className="size-3.5" />
              Download PDF
            </Button>
          ) : null}
          <Button
            size="sm"
            onClick={() => void loadPdf()}
            disabled={!canExportPdf || pdfLoading}
            title={
              canExportPdf
                ? "Buat PDF dengan layout 1section"
                : "Tandai ebook selesai untuk mengaktifkan PDF"
            }
          >
            {pdfLoading ? <Spinner /> : <FileText className="size-3.5" />}
            {pdfLoading ? "Membuat PDF…" : "Generate PDF"}
          </Button>
          <Button
            size="sm"
            variant="secondary"
            onClick={() => setPublishOpen(true)}
          >
            <UploadCloud className="size-3.5" />
            Publish
          </Button>
        </div>
      </div>

      <div>
        <p className="text-[11px] font-semibold uppercase tracking-[0.18em] text-fg-muted">
          Preview &amp; export
        </p>
        <h1 className="mt-1.5 text-2xl font-bold tracking-tight text-fg sm:text-3xl">
          {data.title}
        </h1>
        <p className="mt-1 flex flex-wrap items-center gap-2 text-xs text-fg-muted">
          <span>{data.content.niche}</span>
          <span className="size-1 rounded-full bg-border" />
          <span>{data.content.chapters.length} bab</span>
          <span className="size-1 rounded-full bg-border" />
          <span>{data.content.references.length} referensi</span>
          <span className="size-1 rounded-full bg-border" />
          <span>Diperbarui {formatDate(data.updatedAt)}</span>
        </p>
      </div>

      {published ? (
        <div className="rounded-xl border border-emerald-500/30 bg-emerald-500/10 px-4 py-3 text-xs leading-relaxed text-emerald-700 dark:text-emerald-400">
          Product berhasil dibuat: <strong>{published}</strong>.{" "}
          <Link href="/admin/products" className="font-semibold underline">
            Buka katalog
          </Link>
        </div>
      ) : null}

      {status === "draft" ? (
        <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-amber-500/30 bg-amber-500/10 px-4 py-3">
          <div className="flex items-start gap-3">
            <AlertTriangle className="mt-0.5 size-4 shrink-0 text-amber-600" />
            <p className="text-xs leading-relaxed text-amber-700 dark:text-amber-400">
              Ebook masih berstatus draft. Tandai selesai untuk mengaktifkan
              Generate PDF dan Download PDF.
            </p>
          </div>
          <Button size="sm" onClick={markFinal} disabled={updateProject.isPending}>
            {updateProject.isPending ? (
              <Spinner />
            ) : (
              <CheckCircle2 className="size-3.5" />
            )}
            Tandai selesai
          </Button>
        </div>
      ) : null}

      {statusError ? (
        <div className="rounded-xl border border-red-500/30 bg-red-500/10 px-4 py-3 text-xs leading-relaxed text-red-700 dark:text-red-400">
          {statusError}
        </div>
      ) : null}

      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-border pb-3">
        <p className="text-[11px] font-semibold uppercase tracking-[0.14em] text-fg-muted">
          PDF Preview
        </p>
        <p className="text-[11px] text-fg-muted">
          Dirender server-side dengan PDFKit · A5 (148 × 210 mm).
        </p>
      </div>

      <div>
        {pdfError ? (
          <div className="mb-4 rounded-xl border border-red-500/30 bg-red-500/10 px-4 py-3 text-xs leading-relaxed text-red-700 dark:text-red-400">
            {pdfError}
          </div>
        ) : null}

        {!pdfSrc ? (
          <div className="flex min-h-[420px] flex-col items-center justify-center gap-3 rounded-2xl border border-dashed border-border bg-card px-6 py-12 text-center">
            <span className="grid size-12 place-items-center rounded-2xl bg-surface-muted text-fg-muted">
              <FileText className="size-5" />
            </span>
            <p className="text-sm font-semibold text-fg">
              {canExportPdf && pdfLoading
                ? "Membuat PDF…"
                : "PDF belum dibuat"}
            </p>
            <p className="max-w-sm text-xs leading-relaxed text-fg-muted">
              PDF dibuat langsung oleh server dengan PDFKit, mengikuti layout
              1section: cover, daftar isi, bab, kesimpulan, referensi, dan
              about. Preview ini memakai file PDF yang sama dengan yang
              diunduh, jadi paginasi A5-nya akurat.
            </p>
            {canExportPdf ? (
              <Button
                size="sm"
                onClick={() => void loadPdf()}
                disabled={pdfLoading}
                className="mt-2"
              >
                {pdfLoading ? <Spinner /> : <FileText className="size-3.5" />}
                {pdfLoading ? "Membuat PDF…" : "Generate PDF"}
              </Button>
            ) : (
              <Button
                size="sm"
                onClick={markFinal}
                disabled={updateProject.isPending}
                className="mt-2"
              >
                {updateProject.isPending ? (
                  <Spinner />
                ) : (
                  <CheckCircle2 className="size-3.5" />
                )}
                Tandai selesai dulu
              </Button>
            )}
          </div>
        ) : (
          <div className="rounded-2xl border border-border bg-surface-muted/50 p-3 sm:p-5">
            <div className="mx-auto flex w-full max-w-[595px] flex-wrap items-center justify-between gap-2 pb-3">
              <p className="text-[11px] font-semibold text-fg-muted">
                PDF Preview · A5 · 148 × 210 mm
              </p>
              <div className="flex items-center gap-2">
                <a
                  href={pdfSrc}
                  target="_blank"
                  rel="noreferrer"
                  className="inline-flex items-center gap-1 text-[11px] font-semibold text-fg-muted transition hover:text-fg"
                >
                  <ExternalLink className="size-3" />
                  Buka tab baru
                </a>
                <Button
                  variant="secondary"
                  size="sm"
                  onClick={() => void loadPdf()}
                  disabled={pdfLoading}
                >
                  <RefreshCw
                    className={`size-3 ${pdfLoading ? "animate-spin" : ""}`}
                  />
                  Regenerate
                </Button>
              </div>
            </div>
            <div className="mx-auto w-full max-w-[595px] overflow-hidden rounded-sm border border-border bg-white shadow-[0_1px_2px_rgba(9,9,11,0.08),0_18px_40px_-24px_rgba(9,9,11,0.35)]">
              <iframe
                src={pdfSrc}
                title={`PDF preview ${data.title}`}
                className="aspect-[148/210] w-full bg-white"
              />
            </div>
          </div>
        )}
      </div>

      <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-border bg-card px-4 py-3">
        <p className="text-xs leading-relaxed text-fg-muted">
          Perlu revisi isi? Kembali ke editor — perubahan akan otomatis
          tercermin saat file dibuat ulang.
        </p>
        <div className="flex gap-2">
          <Link
            href={`/admin/builder/${projectId}`}
            className="inline-flex items-center gap-1.5 rounded-lg border border-border bg-card px-3.5 py-2 text-xs font-semibold text-fg transition hover:bg-surface-muted"
          >
            <Pencil className="size-3.5" />
            Edit ebook
          </Link>
          <Link
            href="/admin/builder"
            className="inline-flex items-center gap-1.5 rounded-lg bg-accent px-3.5 py-2 text-xs font-semibold text-accent-fg transition hover:opacity-90"
          >
            Product Builder
          </Link>
        </div>
      </div>

      <PublishModal
        open={publishOpen}
        onClose={() => setPublishOpen(false)}
        projectId={projectId}
        defaultName={data.title}
        defaultSummary={data.content.description}
        defaultNicheName={data.content.niche}
        onPublished={(name) => {
          setPublished(name);
          setPublishOpen(false);
        }}
      />
    </div>
  );
}

function PublishModal({
  open,
  onClose,
  projectId,
  defaultName,
  defaultSummary,
  defaultNicheName,
  onPublished,
}: {
  open: boolean;
  onClose: () => void;
  projectId: string;
  defaultName: string;
  defaultSummary: string;
  defaultNicheName: string;
  onPublished: (name: string) => void;
}) {
  const niches = useAdminNiches();
  const publish = usePublishEbookProject();
  const [error, setError] = useState<string | null>(null);

  const savedNiche = niches.data?.find(
    (niche) =>
      niche.name.trim().toLowerCase() === defaultNicheName.trim().toLowerCase(),
  );

  async function handlePublishSubmit(input: ProductInput) {
    setError(null);
    if (!input.nicheId) {
      setError("Pilih niche terlebih dahulu.");
      return;
    }
    const priceAmount = input.priceAmount ?? 0;
    if (!Number.isFinite(priceAmount) || priceAmount < 0) {
      setError("Harga tidak valid.");
      return;
    }

    const publishInput: PublishEbookInput = {
      nicheId: input.nicheId,
      name: input.name.trim() || undefined,
      slug: input.slug?.trim() || undefined,
      summary: input.summary?.trim() || null,
      description: input.description?.trim() || null,
      priceAmount,
      compareAtAmount: input.compareAtAmount,
      level: input.level,
      features: input.features,
      active: input.active,
    };

    try {
      const product = await publish.mutateAsync({
        id: projectId,
        input: publishInput,
      });
      onPublished(product.name);
    } catch (caught) {
      setError(getApiErrorMessage(caught));
    }
  }

  return (
    <Modal open={open} onClose={onClose} title="Publish ebook ke katalog" wide>
      <div className="space-y-4">
        <p className="rounded-lg bg-surface-muted p-3 text-xs leading-relaxed text-fg-muted">
          PDF akan dibuat ulang dari konten terbaru, diunggah ke penyimpanan
          privat, lalu ditautkan ke product baru. Product juga otomatis
          disinkronkan ke Paddle.
        </p>
        {error ? (
          <p className="rounded-lg bg-red-500/10 px-3 py-2 text-xs text-red-700 dark:text-red-400">
            {error}
          </p>
        ) : null}
        <ProductForm
          niches={niches.data ?? []}
          projectId={projectId}
          initialValues={{
            name: defaultName,
            summary: defaultSummary ?? "",
            description: defaultSummary ?? "",
            nicheId: savedNiche?.id ?? "",
            level: "FOUNDATIONS",
            active: false,
          }}
          onSubmit={handlePublishSubmit}
          onCancel={onClose}
          isSubmitting={publish.isPending}
        />
      </div>
    </Modal>
  );
}

